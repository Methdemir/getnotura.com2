import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const readJson = file => JSON.parse(readFileSync(new URL(file, root), "utf8"));
const locales = readJson("src/i18n/locales.json").filter(locale => locale.publicationStatus === "published");
const routes = readJson("src/i18n/routes.json");
const destinations = readJson("src/i18n/published-destinations.json");
const studioPaths = readJson("src/config/legacy-studio-paths.json");
const rules = [];
const add = (source, target) => {
  rules.push(`${source} ${target} 301`);
  if (source.endsWith("/")) rules.push(`${source.slice(0, -1)} ${target} 301`);
};
add("/notura/", "https://getnotura.com/");
for (const locale of locales) {
  for (const destination of destinations) {
    const suffix = routes[destination].path;
    const path = suffix ? `/${locale.urlPrefix}/${suffix}/` : `/${locale.urlPrefix}/`;
    add(`/notura${path}`, `https://getnotura.com${path}`);
  }
}
for (const path of studioPaths) add(path, `https://sarperstudios.com${path}`);
add("/takip/", "https://sarperstudios.com/takip/");
rules.push("/takip/* https://sarperstudios.com/takip/:splat 301");
writeFileSync(new URL("public/_redirects", root),
  "# Generated by scripts/generate-redirects.mjs. Cloudflare Pages HTTP redirects.\n" + rules.join("\n") + "\n");
console.log(`Generated ${rules.length} compatibility HTTP 301 rules.`);
